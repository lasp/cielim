def calculate_sun_irradiance(scene: cielim.Scene) -> tuple[float, float, float]:
    """
    Calculate the sun irradiance for a given scene using Planck's law.

    Args:
        scene (cielim.Scene): The scene for which to calculate sun irradiance.
    """
    scene_object = scene.get_scene()

    # Planck's law needs wavelengths in meters, the scene stores them in nanometers
    wavelength1 = scene_object.renderParameters.wavelength1 * 1e-9
    wavelength2 = scene_object.renderParameters.wavelength2 * 1e-9
    wavelength3 = scene_object.renderParameters.wavelength3 * 1e-9

    sun_radius = 6.957e8  # Meters
    sun_temperature = 5778.0  # Kelvin
    radiation_constant1 = 1.191e-16  # W * Meters^2
    radiation_constant2 = 1.439e-2  # Meters * K

    wavelength1_radiance = (
        1e-9
        * radiation_constant1
        / np.pow(wavelength1, 5)
        / (np.exp(radiation_constant2 / (wavelength1 * sun_temperature)) - 1.0)
    )
    wavelength2_radiance = (
        1e-9
        * radiation_constant1
        / np.pow(wavelength2, 5)
        / (np.exp(radiation_constant2 / (wavelength2 * sun_temperature)) - 1.0)
    )
    wavelength3_radiance = (
        1e-9
        * radiation_constant1
        / np.pow(wavelength3, 5)
        / (np.exp(radiation_constant2 / (wavelength3 * sun_temperature)) - 1.0)
    )

    sun_distance = np.linalg.norm(scene_object.celestialBodies[0].position)  # Meters
    sun_solid_angle = np.pi * sun_radius**2 / (sun_distance**2)  # Steradians

    wavelength1_irradiance = wavelength1_radiance * sun_solid_angle  # W * Meters^-2 * Nanometer^-1
    wavelength2_irradiance = wavelength2_radiance * sun_solid_angle  # W * Meters^-2 * Nanometer^-1
    wavelength3_irradiance = wavelength3_radiance * sun_solid_angle  # W * Meters^-2 * Nanometer^-1

    return wavelength1_irradiance, wavelength2_irradiance, wavelength3_irradiance


def calculate_photoelectrons(
    total_radiance: tuple[float, float, float], scene: cielim.Scene
) -> tuple[float, float, float]:
    """
    Calculate the number of photoelectrons generated by a scene with no shot noise.

    Args:
        total_radiance tuple[float, float, float]: The total radiance of the scene.
        scene (cielim.Scene): The scene for which to calculate photoelectrons.

    Returns:
        tuple[float, float, float]: The calculated photoelectron values for R, G, and B channels.
    """
    scene_object = scene.get_scene()

    # Calculate lens geometry factors

    aperture_area = np.pi * scene_object.camera.lensModel.apertureRadius**2
    solid_angle = aperture_area / (scene_object.camera.lensModel.focalLength**2)

    pixel_width = scene_object.camera.sensorModel.sensorWidth / scene_object.camera.sensorModel.resolution[0]
    sensor_height = scene_object.camera.sensorModel.sensorHeight / scene_object.camera.sensorModel.resolution[1]

    pixel_area = pixel_width * sensor_height

    # Calculate lighting factors

    transmission1 = scene_object.camera.lensModel.transmission1
    transmission2 = scene_object.camera.lensModel.transmission2
    transmission3 = scene_object.camera.lensModel.transmission3

    wavelength1_energy_inverse = scene_object.renderParameters.wavelength1 * 5.034e15  # Multiply by 1/hc [J^-1 nm^-1]
    wavelength2_energy_inverse = scene_object.renderParameters.wavelength2 * 5.034e15  # Multiply by 1/hc [J^-1 nm^-1]
    wavelength3_energy_inverse = scene_object.renderParameters.wavelength3 * 5.034e15  # Multiply by 1/hc [J^-1 nm^-1]

    exposure_time = scene_object.camera.sensorModel.exposureTime

    # Calculate QE factors

    simpson_factor = np.abs(scene_object.renderParameters.wavelength1 - scene_object.renderParameters.wavelength3) / 6.0

    correction_factor = scene_object.camera.sensorModel.qeCurve.integrationWeightFactor

    qe_curve_r1 = scene_object.camera.sensorModel.qeCurve.redValue1
    qe_curve_r2 = scene_object.camera.sensorModel.qeCurve.redValue2
    qe_curve_r3 = scene_object.camera.sensorModel.qeCurve.redValue3
    qe_curve_g1 = scene_object.camera.sensorModel.qeCurve.greenValue1
    qe_curve_g2 = scene_object.camera.sensorModel.qeCurve.greenValue2
    qe_curve_g3 = scene_object.camera.sensorModel.qeCurve.greenValue3
    qe_curve_b1 = scene_object.camera.sensorModel.qeCurve.blueValue1
    qe_curve_b2 = scene_object.camera.sensorModel.qeCurve.blueValue2
    qe_curve_b3 = scene_object.camera.sensorModel.qeCurve.blueValue3

    # Calculate QE for each channel

    wavelength1_power = solid_angle * pixel_area * transmission1 * total_radiance[0]
    wavelength2_power = solid_angle * pixel_area * transmission2 * total_radiance[1]
    wavelength3_power = solid_angle * pixel_area * transmission3 * total_radiance[2]

    num_w1_electrons_r = wavelength1_power * wavelength1_energy_inverse * exposure_time * qe_curve_r1
    num_w2_electrons_r = wavelength2_power * wavelength2_energy_inverse * exposure_time * qe_curve_r2
    num_w3_electrons_r = wavelength3_power * wavelength3_energy_inverse * exposure_time * qe_curve_r3

    num_w1_electrons_g = wavelength1_power * wavelength1_energy_inverse * exposure_time * qe_curve_g1
    num_w2_electrons_g = wavelength2_power * wavelength2_energy_inverse * exposure_time * qe_curve_g2
    num_w3_electrons_g = wavelength3_power * wavelength3_energy_inverse * exposure_time * qe_curve_g3

    num_w1_electrons_b = wavelength1_power * wavelength1_energy_inverse * exposure_time * qe_curve_b1
    num_w2_electrons_b = wavelength2_power * wavelength2_energy_inverse * exposure_time * qe_curve_b2
    num_w3_electrons_b = wavelength3_power * wavelength3_energy_inverse * exposure_time * qe_curve_b3

    num_electrons_r = simpson_factor * (num_w1_electrons_r + 4 * num_w2_electrons_r + num_w3_electrons_r)
    num_electrons_g = simpson_factor * (num_w1_electrons_g + 4 * num_w2_electrons_g + num_w3_electrons_g)
    num_electrons_b = simpson_factor * (num_w1_electrons_b + 4 * num_w2_electrons_b + num_w3_electrons_b)

    num_electrons_r *= correction_factor
    num_electrons_g *= correction_factor
    num_electrons_b *= correction_factor

    return num_electrons_r, num_electrons_g, num_electrons_b


@pytest.mark.parametrize(
    "brdf, exposure, sun_angle_deg, plane_angle_deg",
    [
        ("Lambertian", 5e-5, 0, 0),
        ("Lambertian", 5e-5, 30, 0),
        ("Lambertian", 5e-5, 60, 0),
        ("Lambertian", 5e-5, 80, 0),
        ("Lambertian", 5e-5, 0, 30),
        ("Lambertian", 5e-5, 0, 60),
        ("Lambertian", 5e-5, 0, 80),
        ("Lambertian", 5e-5, 30, 30),
        ("Lambertian", 5e-5, 60, 30),
        ("Lambertian", 5e-5, 30, 60),
        ("Regolith", 2.5e-4, 0, 0),
        ("Regolith", 2.5e-4, 30, 0),
        ("Regolith", 2.5e-4, 60, 0),
        ("Regolith", 2.5e-4, 80, 0),
        ("Regolith", 2.5e-4, 0, 30),
        ("Regolith", 2.5e-4, 0, 60),
        ("Regolith", 2.5e-4, 0, 80),
        ("Regolith", 2.5e-4, 30, 30),
        ("Regolith", 2.5e-4, 60, 30),
        ("Regolith", 2.5e-4, 30, 60),
    ],
)
def test_brdf(
    cielim_connection: cielim.Connector,
    brdf: str,
    exposure: float,
    sun_angle_deg: float,
    plane_angle_deg: float,
):
    """
    Tests that the BRDFs are correctly applied to the scene and that the calculated radiances match expected values.
    """
    connector = cielim_connection

    scene = default_scene(shape="Plane", distance=2000)

    scene.set_celestial_body_params(1, mesh_brdf=brdf)

    scene_object = scene.get_scene()

    # Move the sun around the y axis while keeping its distance (and irradiance) the same

    sun_angle = np.radians(sun_angle_deg)
    sun_distance = np.linalg.norm(scene_object.celestialBodies[0].position)
    scene.set_celestial_body_params(
        0, position=(sun_distance * np.sin(sun_angle), 0.0, sun_distance * np.cos(sun_angle))
    )

    # Rotate the plane around the y axis through the mesh attitude, which is an MRP (tan(angle / 4) * axis)

    plane_angle = np.radians(plane_angle_deg)
    scene.set_celestial_body_params(1, mesh_attitude=(0.0, np.tan(plane_angle / 4), 0.0))

    # Set exposure low enough that the image doesn't saturate
    scene.set_sensor_params(exposure=exposure)
    # Set gamma to 1 so image stays linear
    scene.set_sensor_params(gamma=1)

    connector.send_init_request()
    connector.send_frame(scene.get_scene())
    image, _, _ = connector.request_image_for_camera_id(1, True, False)

    image = image[..., ::-1]  # Change OpenCV BGR to RGB
    image_normalized = image.astype(np.float64) / np.iinfo(image.dtype).max

    assert (
        np.max(image_normalized) < 0.95
    ), f"Image is saturated ({np.max(image)}) for BRDF {brdf} with sun angle {sun_angle_deg} deg and plane angle {plane_angle_deg} deg, analytic comparison is invalid"

    # Get the median pixel values for each channel from a patch of pixels at the center of the image

    height, width, _ = image.shape

    half_size = 4  # 9 x 9 patch
    center_row, center_col = height // 2, width // 2
    center_patch = (
        slice(center_row - half_size, center_row + half_size + 1),
        slice(center_col - half_size, center_col + half_size + 1),
    )

    image_center = image_normalized[center_patch] ** scene_object.camera.sensorModel.gamma

    image_photoelectrons = tuple(
        np.median(image_center, axis=(0, 1)) * scene_object.camera.sensorModel.fullWellCapacity
    )

    # Calculate the expected number of photoelectrons for each channel for given BRDF and QE curve

    plane_normal = np.array([np.sin(plane_angle), 0.0, np.cos(plane_angle)])
    plane_position = np.array(scene_object.celestialBodies[1].position)

    sun_direction = np.array(scene_object.celestialBodies[0].position) - plane_position
    obs_direction = np.array(scene_object.spacecraft.position) - plane_position

    mu_0 = max(0.0, float(np.dot(plane_normal, sun_direction / np.linalg.norm(sun_direction))))
    mu = max(0.0, float(np.dot(plane_normal, obs_direction / np.linalg.norm(obs_direction))))

    # This isn't actually the geometric albedo, but is instead interpreted as Lambertian or
    # single-scattering albedo depending on the BRDF
    albedo = scene_object.celestialBodies[1].model.geometricAlbedo
    sun_irradiance = calculate_sun_irradiance(scene)

    if brdf == "Lambertian":
        reflectance = albedo * mu_0 / np.pi
    elif brdf == "Regolith":
        regolith_coef = albedo / (4 * np.pi)
        reflectance = regolith_coef * mu_0 / (mu_0 + mu)
    else:
        pytest.fail(f"invalid BRDF given: {brdf}")

    total_radiance = (reflectance * sun_irradiance[0], reflectance * sun_irradiance[1], reflectance * sun_irradiance[2])

    expected_photoelectrons = calculate_photoelectrons(total_radiance, scene)

    np.testing.assert_allclose(
        image_photoelectrons,
        expected_photoelectrons,
        rtol=0.02,
        err_msg=f"Median photoelectrons {image_photoelectrons} did not match expected of {expected_photoelectrons} for BRDF {brdf} (i = {np.degrees(np.arccos(mu_0)):.1f} deg, e = {np.degrees(np.arccos(mu)):.1f} deg)",
    )
